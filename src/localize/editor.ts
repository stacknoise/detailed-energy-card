export type EditorKey = keyof typeof de;

/** Translates an editor text; other languages than German get English. */
export type Tr = (key: EditorKey, ...args: Array<string | number>) => string;

export function makeTr(lang?: string): Tr {
  const texts = lang?.toLowerCase().startsWith("de") ? de : en;
  return (key, ...args) => texts[key].replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ""));
}
